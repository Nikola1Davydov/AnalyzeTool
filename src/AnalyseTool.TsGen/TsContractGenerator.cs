using System.Collections;
using System.ComponentModel;
using System.Reflection;
using System.Text;
using AnalyseTool.Sdk;
using Newtonsoft.Json;
using Newtonsoft.Json.Converters;
using Newtonsoft.Json.Linq;
using Newtonsoft.Json.Serialization;

namespace AnalyseTool.TsGen
{
    /// <summary>
    /// Turns the built-in commands' declared InputType/OutputType into TypeScript. The rules mirror the
    /// wire, not the C# source: outputs go out through Newtonsoft with default settings
    /// (<c>JToken.FromObject</c> in the transports), so a property is named as its contract names it and
    /// is optional only where Newtonsoft leaves it out. Inputs come in through the same serializer, which
    /// matches names case-insensitively and keeps a missing property's initial value — so an input-only
    /// type is written in camelCase (what the page and the MCP schema send) and its nullable and value-typed
    /// properties are optional.
    /// </summary>
    public static class TsContractGenerator
    {
        /// <summary>The assemblies whose commands the page can call without a host-only UI type.</summary>
        public static IReadOnlyList<Assembly> PlatformAssemblies() =>
        [
            Assembly.Load("AnalyseTool.Core"),
            Assembly.Load("AnalyseTool.Tools"),
            Assembly.Load("AnalyseTool.Mcp.Bridge"),
        ];

        public static string Generate() => Generate(PlatformAssemblies());

        public static string Generate(IEnumerable<Assembly> assemblies)
        {
            List<CommandInfo> commands = assemblies
                .SelectMany(LoadableTypes)
                .Where(t => typeof(IRevitTask).IsAssignableFrom(t) && !t.IsAbstract && !t.IsInterface)
                .Select(t => (Type: t, Attr: t.GetCustomAttribute<RevitCommandAttribute>()))
                .Where(c => c.Attr is not null)
                .Select(c => new CommandInfo(
                    string.IsNullOrEmpty(c.Attr!.Name) ? c.Type.Name : c.Attr.Name!,
                    c.Attr.Description, c.Attr.InputType, c.Attr.OutputType))
                .OrderBy(c => c.Name, StringComparer.Ordinal)
                .ToList();

            Emitter emitter = new();
            // Outputs first: a type both sent and received is written by the stricter output rules.
            foreach (CommandInfo c in commands)
                if (c.Output is not null) emitter.MarkOutput(c.Output);

            StringBuilder body = new();
            body.Append("export const commands = {\n");
            foreach (CommandInfo c in commands)
            {
                string output = c.Output is null ? "unknown" : emitter.Reference(c.Output, null);
                WriteDoc(body, "  ", c.Description);
                if (c.Input is null)
                {
                    body.Append($"  {c.Name}: (options?: InvokeOptions) =>\n");
                    body.Append($"    invoke<{output}>(\"{c.Name}\", null, options),\n");
                }
                else
                {
                    string input = emitter.Reference(c.Input, null);
                    string parameter = emitter.AllOptional(c.Input) ? $"input: {input} = {{}}" : $"input: {input}";
                    body.Append($"  {c.Name}: ({parameter}, options?: InvokeOptions) =>\n");
                    body.Append($"    invoke<{output}>(\"{c.Name}\", input, options),\n");
                }
            }
            body.Append("} as const;\n");

            StringBuilder ts = new();
            ts.Append("// <auto-generated>\n");
            ts.Append("// Written by AnalyseTool.TsGen from the [RevitCommand] InputType/OutputType declarations of\n");
            ts.Append("// AnalyseTool.Core, .Tools and .Mcp.Bridge. Do not edit: a Debug build of the Launcher rewrites\n");
            ts.Append("// it, and the tier-1 test TsContractTests fails when it is out of date.\n");
            ts.Append("// </auto-generated>\n");
            ts.Append("/* eslint-disable */\n\n");
            ts.Append("import { invoke, type InvokeOptions } from \"@/RevitBridge\";\n\n");
            emitter.WriteDeclarations(ts);
            ts.Append(body);
            return ts.ToString();
        }

        private sealed record CommandInfo(string Name, string? Description, Type? Input, Type? Output);

        private static IEnumerable<Type> LoadableTypes(Assembly assembly)
        {
            // A few platform types derive from Revit UI types (RevitTaskHub : IExternalEventHandler) and do
            // not load without Revit; none of them is a command.
            try { return assembly.GetTypes(); }
            catch (ReflectionTypeLoadException ex) { return ex.Types.Where(t => t is not null)!; }
        }

        internal static void WriteDoc(StringBuilder sb, string indent, string? text)
        {
            if (string.IsNullOrWhiteSpace(text)) return;
            sb.Append(indent).Append("/** ").Append(text.Replace("*/", "*\\/").Trim()).Append(" */\n");
        }

        private sealed class Emitter
        {
            private static readonly DefaultContractResolver Resolver = new();
            // Per run, not static: NullabilityInfoContext caches without locking.
            private readonly NullabilityInfoContext _nullability = new();

            private readonly HashSet<Type> _outputs = new();
            private readonly Dictionary<Type, string> _names = new();
            private readonly Dictionary<string, Type> _byName = new(StringComparer.Ordinal);
            private readonly SortedDictionary<string, string> _declarations = new(StringComparer.Ordinal);
            private readonly HashSet<Type> _declaring = new();

            /// <summary>Records every object type reachable from an output, before anything is written.</summary>
            public void MarkOutput(Type type)
            {
                type = Nullable.GetUnderlyingType(type) ?? type;
                if (Classify(type) is { } element)
                {
                    if (element.Item is not null) MarkOutput(element.Item);
                    return;
                }
                if (!IsObject(type) || !_outputs.Add(type)) return;
                foreach (JsonProperty p in Properties(type) ?? [])
                    if (p.PropertyType is not null) MarkOutput(p.PropertyType);
            }

            public bool AllOptional(Type type) =>
                Properties(type) is { } props && props.All(p => IsOptional(type, p));

            /// <summary>The TypeScript for a use of <paramref name="type"/>; declares it when needed.</summary>
            public string Reference(Type type, NullabilityInfo? nullability)
            {
                Type? underlying = Nullable.GetUnderlyingType(type);
                if (underlying is not null) return Reference(underlying, null);

                if (Classify(type) is { } shape)
                {
                    NullabilityInfo? itemNullability = shape.Kind == Shape.Array
                        ? nullability?.ElementType ?? (nullability?.GenericTypeArguments is { Length: > 0 } a ? a[^1] : null)
                        : nullability?.GenericTypeArguments is { Length: 2 } d ? d[1] : null;
                    string item = shape.Item is null ? "unknown" : Reference(shape.Item, itemNullability);
                    if (itemNullability?.ReadState == NullabilityState.Nullable && item != "unknown") item += " | null";
                    if (shape.Kind == Shape.Map) return $"Record<string, {item}>";
                    return item.Contains(' ') ? $"({item})[]" : $"{item}[]";
                }

                if (Primitive(type) is { } primitive) return primitive;
                if (type.IsEnum)
                    return type.GetCustomAttribute<JsonConverterAttribute>()?.ConverterType == typeof(StringEnumConverter)
                        ? string.Join(" | ", Enum.GetNames(type).Select(n => $"\"{n}\""))
                        : "number";
                if (!IsObject(type)) return "unknown";
                return Declare(type);
            }

            public void WriteDeclarations(StringBuilder sb)
            {
                foreach (string declaration in _declarations.Values)
                    sb.Append(declaration).Append('\n');
            }

            private string Declare(Type type)
            {
                if (_names.TryGetValue(type, out string? known)) return known;

                string name = TsName(type);
                if (_byName.TryGetValue(name, out Type? other) && other != type)
                    throw new InvalidOperationException(
                        $"Two contract types map to the TypeScript name '{name}': {other.FullName} and {type.FullName}. " +
                        "Rename one of them.");
                _byName[name] = type;
                _names[type] = name;
                if (!_declaring.Add(type)) return name;

                StringBuilder sb = new();
                IList<JsonProperty>? properties = Properties(type);
                if (properties is null)
                {
                    sb.Append($"/** {type.Name} references Revit API types; its shape is checked inside Revit only. */\n");
                    sb.Append($"export type {name} = unknown;\n");
                    _declarations[name] = sb.ToString();
                    return name;
                }

                bool output = _outputs.Contains(type);
                sb.Append($"export interface {name} {{\n");
                foreach (JsonProperty p in properties)
                {
                    MemberInfo? member = Member(type, p);
                    NullabilityInfo? info = member switch
                    {
                        PropertyInfo pi => _nullability.Create(pi),
                        FieldInfo fi => _nullability.Create(fi),
                        _ => null,
                    };
                    string tsType = Reference(p.PropertyType!, info);
                    bool nullable = IsNullable(p.PropertyType!, info);
                    bool optional = IsOptional(type, p);
                    // An output property that Newtonsoft leaves out when null is never null on the wire.
                    bool ignoresNull = output && optional && nullable;
                    if (nullable && !ignoresNull && tsType != "unknown") tsType += " | null";

                    WriteDoc(sb, "  ", member?.GetCustomAttribute<DescriptionAttribute>()?.Description);
                    sb.Append($"  {PropertyName(type, p, member)}{(optional ? "?" : "")}: {tsType};\n");
                }
                sb.Append("}\n");
                _declarations[name] = sb.ToString();
                return name;
            }

            private bool IsOptional(Type owner, JsonProperty p)
            {
                if (_outputs.Contains(owner))
                    return p.NullValueHandling == NullValueHandling.Ignore
                        || (p.DefaultValueHandling is { } d && d.HasFlag(DefaultValueHandling.Ignore));

                // Input: the serializer keeps the initial value of anything not sent.
                Type t = p.PropertyType!;
                if (Nullable.GetUnderlyingType(t) is not null || t.IsValueType) return true;
                MemberInfo? member = Member(owner, p);
                NullabilityInfo? info = member switch
                {
                    PropertyInfo pi => _nullability.Create(pi),
                    FieldInfo fi => _nullability.Create(fi),
                    _ => null,
                };
                return info?.ReadState == NullabilityState.Nullable;
            }

            private string PropertyName(Type owner, JsonProperty p, MemberInfo? member)
            {
                bool explicitName = member?.GetCustomAttribute<JsonPropertyAttribute>()?.PropertyName is not null;
                if (explicitName || _outputs.Contains(owner)) return p.PropertyName!;
                string n = p.PropertyName!;
                return n.Length == 0 ? n : char.ToLowerInvariant(n[0]) + n[1..];
            }

            private static bool IsNullable(Type type, NullabilityInfo? info) =>
                Nullable.GetUnderlyingType(type) is not null
                || (!type.IsValueType && info?.ReadState == NullabilityState.Nullable);

            private static MemberInfo? Member(Type owner, JsonProperty p) =>
                (MemberInfo?)owner.GetProperty(p.UnderlyingName!, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance)
                ?? owner.GetField(p.UnderlyingName!, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);

            /// <summary>The serialized properties, or null when the type cannot be inspected without Revit.</summary>
            private static IList<JsonProperty>? Properties(Type type)
            {
                try
                {
                    if (Resolver.ResolveContract(type) is not JsonObjectContract contract) return [];
                    List<JsonProperty> props = contract.Properties.Where(p => !p.Ignored && (p.Readable || p.Writable)).ToList();
                    foreach (JsonProperty p in props) Touch(p.PropertyType);
                    return props;
                }
                catch (Exception ex) when (ex is FileNotFoundException or FileLoadException or TypeLoadException)
                {
                    return null;
                }
            }

            private static void Touch(Type? type)
            {
                // Reaching into a member type is what throws when that type lives in the Revit API.
                if (type is null) return;
                _ = type.GetProperties();
                foreach (Type arg in type.IsGenericType ? type.GetGenericArguments() : []) Touch(arg);
            }

            private static string TsName(Type type)
            {
                string Simple(Type t)
                {
                    string n = t.Name;
                    int tick = n.IndexOf('`');
                    if (tick >= 0) n = n[..tick] + "Of" + string.Concat(t.GetGenericArguments().Select(Simple));
                    return n;
                }
                // Nested request records are named after their command: GetParameterReport.Request ->
                // GetParameterReportRequest.
                string name = Simple(type);
                for (Type? outer = type.DeclaringType; outer is not null; outer = outer.DeclaringType)
                    name = outer.Name + name;
                return name;
            }

            private static string? Primitive(Type type)
            {
                if (type == typeof(string) || type == typeof(char) || type == typeof(Guid) || type == typeof(DateTime)
                    || type == typeof(DateTimeOffset) || type == typeof(TimeSpan) || type == typeof(Uri)
                    || type == typeof(byte[]))
                    return "string";
                if (type == typeof(bool)) return "boolean";
                if (type == typeof(byte) || type == typeof(sbyte) || type == typeof(short) || type == typeof(ushort)
                    || type == typeof(int) || type == typeof(uint) || type == typeof(long) || type == typeof(ulong)
                    || type == typeof(float) || type == typeof(double) || type == typeof(decimal))
                    return "number";
                if (type == typeof(object) || typeof(JToken).IsAssignableFrom(type)) return "unknown";
                return null;
            }

            private enum Shape { Array, Map }

            private static (Shape Kind, Type? Item)? Classify(Type type)
            {
                if (type == typeof(string) || type == typeof(byte[]) || typeof(JToken).IsAssignableFrom(type)) return null;
                if (type.IsArray) return (Shape.Array, type.GetElementType());

                Type? dictionary = Implemented(type, typeof(IDictionary<,>)) ?? Implemented(type, typeof(IReadOnlyDictionary<,>));
                if (dictionary is not null) return (Shape.Map, dictionary.GetGenericArguments()[1]);
                if (typeof(IDictionary).IsAssignableFrom(type)) return (Shape.Map, null);

                Type? enumerable = Implemented(type, typeof(IEnumerable<>));
                if (enumerable is not null) return (Shape.Array, enumerable.GetGenericArguments()[0]);
                if (typeof(IEnumerable).IsAssignableFrom(type)) return (Shape.Array, null);
                return null;
            }

            private static Type? Implemented(Type type, Type generic)
            {
                if (type.IsGenericType && type.GetGenericTypeDefinition() == generic) return type;
                return type.GetInterfaces().FirstOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == generic);
            }

            private static bool IsObject(Type type) =>
                !type.IsPrimitive && !type.IsEnum && !type.IsInterface && Primitive(type) is null && Classify(type) is null;
        }
    }
}
